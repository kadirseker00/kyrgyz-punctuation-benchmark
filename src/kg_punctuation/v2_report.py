"""Aggregate the v2 main panel (experiments/v2_main/*/scores.json) into report tables.

    PYTHONPATH=src .venv/bin/python -m kg_punctuation.v2_report

Writes reports/v2/main_panel.csv (one row per job x test source, with per-class P/R/F1),
reports/v2/main_panel.md, and reports/v2/tables/*.tex fragments used by the manuscript.
"""

from __future__ import annotations

import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PANEL = ROOT / "experiments/v2_main"
OUT = ROOT / "reports/v2"
SOURCES = ["kyrgyznews", "wikipedia_ky"]
SHORT = {"kyrgyznews": "news", "wikipedia_ky": "wiki"}
NAME = {"kyrgyznews": "News", "wikipedia_ky": "Wikipedia"}
LABELS = ["S", "C", "P"]

# (family, display name, job prefix); job = f"{prefix}_{news|wiki}" for trained models.
MODELS = [
    ("Classical", "Balanced LR", "logreg_balanced"),
    ("Classical", "Balanced SGD-LR", "sgd_log_balanced"),
    ("Neural", "CNN 2$\\times$128", "cnn_small"),
    ("Neural", "CNN 4$\\times$256", "cnn_deep"),
    ("Pretrained", "KyrgyzBERT", "kyrgyzbert"),
    ("Pretrained", "KyrgyzBERT2", "kyrgyzbert2"),
    ("Ours", "KG-Punct-XLMR", "xlmr"),
]
EXTERNAL = [("External (zero-shot)", "KyrgyzBERT-PR", "external_last")]
MIXED = [("Ours", "KG-Punct-XLMR-Mixed (3,200+3,200)", "xlmr_mixed"),
         ("Ours", "KG-Punct-XLMR-Mixed (1,600+1,600)", "xlmr_mixed_matched")]


def load(job: str) -> dict | None:
    path = PANEL / job / "scores.json"
    return json.loads(path.read_text()) if path.exists() else None


def pct(x: float) -> str:
    return f"{100 * x:.2f}"


def rows() -> list[dict]:
    out = []
    for family, name, prefix in MODELS:
        for train in SOURCES:
            job = f"{prefix}_{SHORT[train]}"
            scores = load(job)
            if scores:
                for test, s in scores.items():
                    out.append(_row(family, name, job, train, test, s))
    for family, name, job in EXTERNAL + MIXED:
        scores = load(job)
        if scores:
            train = "none" if job.startswith("external") else "mixed"
            for test, s in scores.items():
                out.append(_row(family, name, job, train, test, s))
    return out


def _row(family, name, job, train, test, s) -> dict:
    row = {"family": family, "model": name, "job": job, "train": train, "test": test,
           "setting": "within" if train == test else ("zero-shot" if train == "none" else ("mixed" if train == "mixed" else "transfer")),
           "words": s["words"], "accuracy": s["accuracy"], "macro_precision": s["macro_precision"],
           "macro_recall": s["macro_recall"], "macro_f1": s["macro_f1"]}
    for label in LABELS:
        for metric in ("precision", "recall", "f1"):
            row[f"{label}_{metric}"] = s["per_class"][label][metric]
        row[f"{label}_support"] = s["per_class"][label]["support"]
    return row


def seeds(source: str) -> dict:
    jobs = [f"xlmr_{SHORT[source]}", f"xlmr_{SHORT[source]}_s43", f"xlmr_{SHORT[source]}_s44"]
    values = [load(j)[source]["macro_f1"] for j in jobs if load(j)]
    return {"jobs": jobs, "macro_f1": values,
            "mean": statistics.mean(values) if values else None,
            "sd": statistics.stdev(values) if len(values) > 1 else None}


def latex_main(data: list[dict]) -> str:
    def cell(job, test, key="macro_f1"):
        r = next((r for r in data if r["job"] == job and r["test"] == test), None)
        return pct(r[key]) if r else "--"

    lines = [
        "% Generated by kg_punctuation.v2_report; do not edit by hand.",
        "\\begin{tabular}{llrrrrrr}", "\\toprule",
        " & & \\multicolumn{3}{c}{News test} & \\multicolumn{3}{c}{Wikipedia test} \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
        "Family & Model & Macro-F1 & Comma F1 & Transfer & Macro-F1 & Comma F1 & Transfer \\\\", "\\midrule",
    ]
    for family, name, prefix in MODELS:
        news, wiki = f"{prefix}_news", f"{prefix}_wiki"
        lines.append(f"{family} & {name} & {cell(news, 'kyrgyznews')} & {cell(news, 'kyrgyznews', 'C_f1')} & "
                     f"{cell(wiki, 'kyrgyznews')} & {cell(wiki, 'wikipedia_ky')} & {cell(wiki, 'wikipedia_ky', 'C_f1')} & "
                     f"{cell(news, 'wikipedia_ky')} \\\\")
    lines.append("\\midrule")
    for family, name, job in MIXED + EXTERNAL:
        lines.append(f"{family} & {name} & {cell(job, 'kyrgyznews')} & {cell(job, 'kyrgyznews', 'C_f1')} & -- & "
                     f"{cell(job, 'wikipedia_ky')} & {cell(job, 'wikipedia_ky', 'C_f1')} & -- \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def latex_per_class(data: list[dict]) -> str:
    lines = ["% Generated by kg_punctuation.v2_report; do not edit by hand.",
             "\\begin{tabular}{lrrrrrrrrrrr}", "\\toprule",
             " & \\multicolumn{3}{c}{Comma (\\texttt{C})} & \\multicolumn{3}{c}{Period (\\texttt{P})}"
             " & \\multicolumn{3}{c}{No punct.\\ (\\texttt{S})} & \\multicolumn{2}{c}{Macro} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}\\cmidrule(lr){11-12}",
             "Model (train $\\rightarrow$ test) & Pr & Re & F1 & Pr & Re & F1 & Pr & Re & F1 & Pr & Re \\\\"]
    order = {"within": 0, "transfer": 1, "mixed": 2, "zero-shot": 3}
    for test in SOURCES:
        lines += ["\\midrule", f"\\multicolumn{{12}}{{l}}{{\\textit{{{NAME[test]} test split}}}} \\\\"]
        for r in sorted((r for r in data if r["test"] == test), key=lambda r: (order[r["setting"]], _rank(r))):
            if r["setting"] == "within":
                label = r["model"]
            elif r["setting"] == "transfer":
                label = f"{r['model']} ({NAME[r['train']]}$\\rightarrow$)"
            else:
                label = r["model"]
            cells = [pct(r[f"{l}_{m}"]) for l in ("C", "P", "S") for m in ("precision", "recall", "f1")]
            cells += [pct(r["macro_precision"]), pct(r["macro_recall"])]
            lines.append(" & ".join([label] + cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def _rank(r: dict) -> int:
    names = [m[1] for m in MODELS] + [m[1] for m in MIXED] + [m[1] for m in EXTERNAL]
    return names.index(r["model"])


def main() -> None:
    data = rows()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tables").mkdir(exist_ok=True)
    with (OUT / "main_panel.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(data[0]))
        writer.writeheader()
        writer.writerows(data)
    seed_summary = {s: seeds(s) for s in SOURCES}
    (OUT / "seeds_xlmr.json").write_text(json.dumps(seed_summary, indent=2), encoding="utf-8")
    paper_tables = ROOT / "paper/R2/ACM_KG_puctuation/tables"
    paper_tables.mkdir(parents=True, exist_ok=True)
    for directory in (OUT / "tables", paper_tables):
        (directory / "main_panel_v2.tex").write_text(latex_main(data), encoding="utf-8")
        (directory / "per_class_v2.tex").write_text(latex_per_class(data), encoding="utf-8")
    md = ["# v2 main panel", "", "Generated by `kg_punctuation.v2_report` from `experiments/v2_main/*/scores.json`.", "",
          "| Model | Job | Train | Test | Setting | Words | Macro-F1 | Comma F1 | Period F1 | Macro P | Macro R |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in data:
        md.append(f"| {r['model']} | {r['job']} | {r['train']} | {r['test']} | {r['setting']} | {r['words']} | "
                  f"{pct(r['macro_f1'])} | {pct(r['C_f1'])} | {pct(r['P_f1'])} | {pct(r['macro_precision'])} | {pct(r['macro_recall'])} |")
    md += ["", "## XLM-R seeds (42 = main row, 43, 44)", ""]
    for s, v in seed_summary.items():
        md.append(f"- {NAME[s]}: " + ", ".join(pct(x) for x in v["macro_f1"]) +
                  (f"; mean {pct(v['mean'])} ± {pct(v['sd'])} (sample SD)" if v["sd"] is not None else ""))
    (OUT / "main_panel.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
